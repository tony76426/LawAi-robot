"""LawAI retrieval: legacy FAQ text, reviewed legal sources, safe hybrid ranking.

Legacy vector_database.json has synthetic-looking vectors; this module NEVER uses them.
An offline, model-tagged OpenAI embedding index may be generated by scripts/build_index.py.
"""
from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from pathlib import Path
import json
import math
import re
import unicodedata

ROOT = Path(__file__).resolve().parent
EMBEDDING_MODEL = "text-embedding-3-small"
MIN_KEYWORD_SCORE = 0.43
MIN_VECTOR_SCORE = 0.60
LEGAL_KINDS = {"law", "judgment"}


@dataclass(frozen=True)
class Record:
    id: str
    title: str
    content: str
    kind: str = "faq"
    source_url: str = ""
    review_status: str = "unreviewed"
    reviewed_at: str = ""
    reviewed_by: str = ""

    @property
    def approved_legal(self) -> bool:
        return (self.kind in LEGAL_KINDS
                and self.review_status == "approved"
                and self.source_url.startswith("https://")
                and bool(self.reviewed_at) and bool(self.reviewed_by))

    @property
    def embedding_text(self) -> str:
        # Marketing FAQ answers are not legal authority; index their question only.
        return self.title if self.kind == "faq" else (self.title + "\n" + self.content[:6000])

    @property
    def keyword_text(self) -> str:
        return self.title if self.kind == "faq" else self.embedding_text


def load_records(root: Path = ROOT) -> list[Record]:
    records = []
    legacy_path = root / "vector_database.json"
    if legacy_path.is_file():
        legacy = json.loads(legacy_path.read_text(encoding="utf-8"))
        if not isinstance(legacy, list):
            raise ValueError("Legacy FAQ must be a JSON array")
        for pos, item in enumerate(legacy, 1):
            question = str(item.get("question", "")).strip()
            answer = str(item.get("answer", "")).strip()
            if question and answer:
                # Deliberately discard item["vector"]. It is NOT a valid indexed embedding.
                records.append(Record(id=f"faq-{pos:03d}", title=question,
                                      content=answer, kind="faq"))
    sources_path = root / "knowledge" / "legal_sources.json"
    if sources_path.is_file():
        sources = json.loads(sources_path.read_text(encoding="utf-8"))
        if not isinstance(sources, list):
            raise ValueError("Legal sources must be a JSON array")
        for item in sources:
            if not isinstance(item, dict) or item.get("kind") not in LEGAL_KINDS:
                continue
            ident, title, body = (str(item.get(k, "")).strip()
                                  for k in ("id", "title", "content"))
            if not ident or not title or not body:
                continue
            records.append(Record(
                id=ident, title=title, content=body,
                kind=item["kind"], source_url=str(item.get("source_url", "")).strip(),
                review_status=str(item.get("review_status", "unreviewed")).strip(),
                reviewed_at=str(item.get("reviewed_at", "")).strip(),
                reviewed_by=str(item.get("reviewed_by", "")).strip(),
            ))
    if len({r.id for r in records}) != len(records):
        raise ValueError("Duplicate knowledge record IDs")
    return records


def fingerprint(records: list[Record]) -> str:
    payload = [{"id": r.id, "text": r.embedding_text, "kind": r.kind,
                "review_status": r.review_status} for r in records]
    raw = json.dumps(payload, ensure_ascii=False, sort_keys=True,
                     separators=(",", ":")).encode("utf-8")
    return sha256(raw).hexdigest()


def load_index(records: list[Record], path: Path, model: str) -> tuple[dict, str]:
    if not path.is_file():
        return {}, "missing"
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
        if (doc.get("version") != 1 or doc.get("model") != model
                or doc.get("fingerprint") != fingerprint(records)):
            return {}, "stale_or_incompatible"
        embeddings = doc["embeddings"]
        if set(embeddings) != {r.id for r in records}:
            return {}, "id_mismatch"
        expected_dim = doc["dimensions"]
        if not isinstance(expected_dim, int) or expected_dim < 10:
            return {}, "invalid_dimensions"
        for vector in embeddings.values():
            if not isinstance(vector, list) or len(vector) != expected_dim:
                return {}, "invalid_vectors"
            if not all(isinstance(x, (int, float)) and math.isfinite(x) for x in vector):
                return {}, "nonfinite_vectors"
            norm = math.sqrt(sum(x*x for x in vector))
            if not 0.98 <= norm <= 1.02:
                return {}, "non_normalized_vectors"
        return embeddings, "ready"
    except (ValueError, KeyError, TypeError, OSError):
        return {}, "invalid_index"


def normalize_text(text: str) -> str:
    text = unicodedata.normalize("NFKC", text).lower()
    for filler in ("請問一下", "我想知道", "我想問", "請問", "我想", "我要",
                   "能不能", "可不可以", "可以幫我", "你們", "怎麼辦", "如何", "謝謝"):
        text = text.replace(filler, " ")
    return text


def tokens(text: str) -> set[str]:
    parts = re.findall(r"[\u4e00-\u9fff]+|[a-z0-9]+", normalize_text(text))
    out: set[str] = set()
    for part in parts:
        if re.fullmatch(r"[\u4e00-\u9fff]+", part):
            if len(part) == 1:
                out.add(part)
            else:
                out.update(part[i:i+2] for i in range(len(part)-1))
        elif len(part) > 1:
            out.add(part)
    return out


def lexical_score(question: str, source: str) -> float:
    q = tokens(question)
    if not q:
        return 0.0
    d = tokens(source)
    if not d:
        return 0.0
    coverage = len(q & d) / len(q)
    # Penalize an incidental single-bigram overlap in otherwise unrelated queries.
    if len(q & d) == 1 and len(q) >= 3:
        coverage *= 0.5
    return coverage


def vector_similarity(a: list[float], b: list[float]) -> float:
    if len(a) != len(b) or not a:
        return 0.0
    anorm = math.sqrt(sum(x*x for x in a))
    bnorm = math.sqrt(sum(x*x for x in b))
    if anorm == 0 or bnorm == 0:
        return 0.0
    return sum(x*y for x, y in zip(a, b)) / (anorm * bnorm)


def rank_records(question: str, records: list[Record],
                 embeddings: dict | None = None,
                 query_vector: list[float] | None = None,
                 limit: int = 5) -> list[dict]:
    if not question.strip() or not tokens(question):
        return []
    semantic = bool(embeddings and query_vector)
    candidates = []
    for record in records:
        lexical = lexical_score(question, record.keyword_text)
        vector = (max(0.0, vector_similarity(query_vector, embeddings[record.id]))
                  if semantic and record.id in embeddings else 0.0)
        if lexical < MIN_KEYWORD_SCORE and vector < MIN_VECTOR_SCORE:
            continue
        score = (0.45 * lexical + 0.55 * vector) if semantic else lexical
        candidates.append({
            "id": record.id, "question": record.title,
            "kind": record.kind, "source_url": record.source_url or None,
            "approved_legal": record.approved_legal,
            "review_status": record.review_status,
            "score": round(score, 4), "keyword_score": round(lexical, 4),
            "semantic_score": round(vector, 4) if semantic else None,
            "_record": record,
        })
    candidates.sort(key=lambda item: (item["score"], item["keyword_score"]), reverse=True)
    return candidates[:max(1, min(limit, 10))]


def public_hit(hit: dict) -> dict:
    return {k: v for k, v in hit.items() if k != "_record"}


def authoritative_hits(hits: list[dict]) -> list[dict]:
    return [hit for hit in hits if hit["approved_legal"]]
